function shade_analysis_window(ax,windowKm,yLimits)
    % Pale background identifies the fixed averaging window in both plots.
    patch(ax,[windowKm(1) windowKm(2) windowKm(2) windowKm(1)], ...
        [yLimits(1) yLimits(1) yLimits(2) yLimits(2)], ...
        [0.84 0.91 0.97],'FaceAlpha',0.32,'EdgeColor','none', ...
        'HandleVisibility','off','HitTest','off');
    hold(ax,'on');
end

function map_style(ax,v)
    % The two maps always have exactly the same amplitude/color reference.
    set(ax,'YDir','normal','XLim',[0 v.x(end)], ...
        'YLim',[0 v.z(end)],'CLim',v.colorLimitsDb, ...
        'FontName','Arial','FontSize',12,'Box','off', ...
        'TickDir','out');
    colormap(ax,parula(256));
    xlabel(ax,'Range (km)');
    ylabel(ax,'Height above ideal sea (m)');
end

function add_result_band(fig,v)
    navy=[0.06 0.22 0.43];
    statement=sprintf(['%.0f–%.0f km spatial mean intensity ratio ' ...
        '(duct / standard): %+.2f dB'], ...
        v.windowKm(1),v.windowKm(2),v.windowRatioDb);
    annotation(fig,'textbox',[0.08 0.099 0.84 0.040], ...
        'String',statement,'EdgeColor','none', ...
        'BackgroundColor',[0.95 0.97 0.99], ...
        'FontName','Arial','FontSize',13,'Color',navy, ...
        'FontWeight','bold','HorizontalAlignment','center', ...
        'VerticalAlignment','middle');
end

function add_footer(fig,leftLabel,rightLabel)
