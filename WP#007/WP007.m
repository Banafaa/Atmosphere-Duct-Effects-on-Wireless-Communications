%% WP007 - When Does an Atmospheric Duct Improve a Receiver-Height Field?
% Author: Mohammed Banafaa
% Series: Wireless Propagation Visuals - WP-007
%
% Two stationary, one-way, narrow-angle SSPE solutions use the same source,
% sea boundary, numerical grid, filter and absorber. Only modified
% refractivity M(z) differs. The duct is an idealized 60 m / 20 M-unit
% surface-based profile; the standard atmosphere has dM/dz = +0.118
% M-units/m everywhere. A common launch-field amplitude normalizes both
% displays. A positive comparison means greater modeled |u|^2 at the
% specified 40 m receiver height, not calibrated link improvement.
% The solver subtracts M at the source height as a constant phase anchor
% in each case; this does not change field intensity or the comparison.
%
% The solver uses the WP-006 symmetric refractivity half-steps, Fourier
% diffraction, odd ideal-PEC image, angular taper, and fixed-height sponge.
% GIF frames sample range through two fixed frequency-domain solutions;
% they do not depict temporal fading or atmospheric evolution.
%
% Run WP007 in MATLAB R2024b from any current folder. It creates Figures
% next to this script, with PNG, GIF, editable FIG, CSV and MAT outputs.
% Base MATLAB only; no external data or optional toolbox is required.
%
% Limitations: idealized Gaussian aperture and smooth PEC sea; narrow-angle
% 2-D scalar PE; finite absorbing domain. Relative fields and PE intensity
% ratios do not establish measured received power, reliability, path loss,
% or a usable coverage distance.
%
% References: O. Ozgun et al., Comput. Phys. Commun. 182 (2011) 2638-2654;
% M. Levy, Parabolic Equation Methods for Electromagnetic Wave Propagation,
% IEE, 2000; ITU-R P.834-9, Effects of tropospheric refraction, 2017.

