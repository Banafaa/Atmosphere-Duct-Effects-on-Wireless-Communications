            [-v.comparisonSpanDb v.comparisonSpanDb], ...
            ':','Color',orange,'LineWidth',1.1);
        h.delta=plot(axDelta,0,v.enhancementDb(1),'o', ...
            'MarkerFaceColor',orange,'MarkerEdgeColor','w', ...
            'MarkerSize',10);
