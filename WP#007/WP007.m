%% Local functions
function validate_cfg(c,heights)
    % Guard grid alignment and the fixed physical configuration.
    assert(c.frequencyGHz==3.5 && c.ductDeficitM==20 && ...
        c.ductTopM==60 && c.rangeMaxKm==100);
    assert(strcmp(c.atmosphere,'surface_duct') || ...
        strcmp(c.atmosphere,'standard'));
    assert(strcmp(c.lowerBoundary,'horizontal_PEC_Dirichlet'));
    assert(c.txHeightM>0 && c.txHeightM<c.ductTopM);
    assert(c.sourceSigmaM/c.dzM>=3, ...
        'Source width under-resolved on the chosen height grid.');
    assert(c.observationTopM==400 && ...
        c.absorberStartM>=500 && c.absorberStartM<=700 && ...
        c.ceilingM>c.absorberStartM+100);
    assert(all(heights>0 & heights<c.ductTopM));
    assert(abs(c.ceilingM/c.dzM-round(c.ceilingM/c.dzM))<1e-9);
    assert(abs(c.ductTopM/c.dzM-round(c.ductTopM/c.dzM))<1e-9);
    assert(abs(c.observationTopM/c.dzM- ...
        round(c.observationTopM/c.dzM))<1e-9);
    assert(abs(c.rangeMaxKm*1000/c.dxM- ...
        round(c.rangeMaxKm*1000/c.dxM))<1e-9);
    assert(abs(c.saveSpacingM/c.dxM- ...
        round(c.saveSpacingM/c.dxM))<1e-9);
    assert(c.angularCutoffDeg>=4 && c.angularCutoffDeg<=6);
end

function M = modified_refractivity(z,c)
    % The atmosphere selector is the ONLY case-dependent solver input.
    % Preserve the WP-006 duct expression exactly for the ducted case.
    if strcmp(c.atmosphere,'surface_duct')
        M = c.Msurface-(c.ductDeficitM/c.ductTopM)* ...
            min(z,c.ductTopM)+c.MgradientAbovePerM* ...
            max(z-c.ductTopM,0);
    else
        M = c.Msurface+c.MgradientAbovePerM*z;
    end
end

function u = launch_field(zFull,zPositive,c)
    % Unit-integral Gaussian aperture with its odd PEC image.
    za=abs(zFull);
    source=exp(-0.5*((za-c.txHeightM)/c.sourceSigmaM).^2);
    image=exp(-0.5*((za+c.txHeightM)/c.sourceSigmaM).^2);
    % Odd field for horizontal polarization on ideal smooth PEC sea.
    u=sign(zFull).*(source-image).*exp( ...
        1i*(2*pi*c.frequencyGHz*1e9/c.c0)* ...
        sind(c.launchElevationDeg)*(za-c.txHeightM));
    nHalf=numel(zPositive);
    u=complex(u/sqrt(trapz(zPositive,abs(u(nHalf+1:end)).^2)));
end
function out = run_case_sspe(c,heights,keepField)
    % Strang SSPE on a mirrored FFT domain; optionally retain each column.
    validate_cfg(c,heights);
    nHalf=round(c.ceilingM/c.dzM);
    zFull=(-nHalf:nHalf-1)'*c.dzM;
    z=(0:nHalf-1)'*c.dzM;
    positive=(nHalf+1:2*nHalf)';
    k0=2*pi*c.frequencyGHz*1e9/c.c0;
    dxKm=c.dxM/1000;
    nSteps=round(c.rangeMaxKm*1000/c.dxM);
    stride=round(c.saveSpacingM/c.dxM);
    nSaved=round(nSteps/stride)+1;
    assert(abs(nSteps/stride-round(nSteps/stride))<1e-9);
    M=modified_refractivity(abs(zFull),c);
    Mref=modified_refractivity(c.txHeightM,c);
    mediumHalf=exp(1i*k0*1e-6*(M-Mref)*c.dxM/2);
    n=2*nHalf;
    kz=(2*pi/(n*c.dzM))*[0:n/2-1 -n/2:-1]';
    diffraction=exp(-1i*kz.^2*c.dxM/(2*k0));
    cutoff=k0*sind(c.angularCutoffDeg);
    beginTaper=c.angularTaperStartFraction*cutoff;
    ak=abs(kz);
    angularWindow=ones(n,1);
    t=ak>beginTaper & ak<cutoff;
    q=(ak(t)-beginTaper)/(cutoff-beginTaper);
    angularWindow(t)=exp(-c.angularAlphaPerKm*dxKm* ...
        (q.^2.*(3-2*q)));
    angularWindow(ak>=cutoff)=0;
    alphaPerKm=c.absorberAlphaAtScalePerKm* ...
        (max(abs(zFull)-c.absorberStartM,0)/ ...
        c.absorberScaleM).^c.absorberPower;
    absorber=exp(-alphaPerKm*dxKm);
    u=launch_field(zFull,z,c);
    out=struct();
    out.rangeKm=(0:nSaved-1)'*c.saveSpacingM/1000;
    out.heightM=z;
    out.sampleHeightsM=heights(:);
    out.receiverComplex=complex(zeros(numel(heights),nSaved));
    out.ductIntensity=zeros(nSaved,1);
    out.outsidePassiveIntensity=zeros(nSaved,1);
    out.passiveIntensity=zeros(nSaved,1);
    out.absorberIntensity=zeros(nSaved,1);
    out.totalIntensity=zeros(nSaved,1);
    out.confinement=zeros(nSaved,1);
    out.fullConfinement=zeros(nSaved,1);
    out.topGuardFraction=zeros(nSaved,1);
    out.boundaryResidual=zeros(nSaved,1);
    out.cumulativeSpongeLoss=zeros(nSaved,1);
    out.cumulativeAngularLoss=zeros(nSaved,1);
    if keepField
        out.complexField=complex(zeros(nHalf,nSaved));
    else
        out.complexField=complex([]);
    end
    ductEnd=round(c.ductTopM/c.dzM)+1;
    passiveEnd=round(c.observationTopM/c.dzM)+1;
    spongeBegin=round(c.absorberStartM/c.dzM)+1;
    guardBegin=find(z>=c.ceilingM-c.topGuardDepthM,1);
    accumulatedSponge=0;
    accumulatedAngular=0;
    saved=0;
    for step=0:nSteps
        if mod(step,stride)==0
            saved=saved+1;
            up=u(positive);
            intensity=abs(up).^2;
            out.receiverComplex(:,saved)=interp1(z,up,heights(:));
            out.ductIntensity(saved)= ...
                trapz(z(1:ductEnd),intensity(1:ductEnd));
            out.passiveIntensity(saved)= ...
                trapz(z(1:passiveEnd),intensity(1:passiveEnd));
            out.outsidePassiveIntensity(saved)= ...
                out.passiveIntensity(saved)-out.ductIntensity(saved);
            out.absorberIntensity(saved)= ...
                trapz(z(spongeBegin:end),intensity(spongeBegin:end));
            out.totalIntensity(saved)=trapz(z,intensity);
            out.confinement(saved)=out.ductIntensity(saved)/ ...
                max(out.passiveIntensity(saved),realmin);
            out.fullConfinement(saved)=out.ductIntensity(saved)/ ...
                max(out.totalIntensity(saved),realmin);
            out.topGuardFraction(saved)= ...
                trapz(z(guardBegin:end),intensity(guardBegin:end))/ ...
                max(out.totalIntensity(saved),realmin);
            out.boundaryResidual(saved)=abs(u(nHalf+1))/ ...
                max(max(abs(u)),realmin);
            out.cumulativeSpongeLoss(saved)=accumulatedSponge;
            out.cumulativeAngularLoss(saved)=accumulatedAngular;
            if keepField, out.complexField(:,saved)=up; end
        end
        if step==nSteps, break; end
        u=mediumHalf.*u;
        before=c.dzM*sum(abs(u).^2)/2;
        u=ifft(fft(u).*diffraction.*angularWindow);
        afterAngular=c.dzM*sum(abs(u).^2)/2;
        accumulatedAngular=accumulatedAngular+max(0,before-afterAngular);
        u=absorber.*mediumHalf.*u;
        afterSponge=c.dzM*sum(abs(u).^2)/2;
        accumulatedSponge=accumulatedSponge+ ...
            max(0,afterAngular-afterSponge);
    end
    assert(saved==nSaved && all(isfinite(out.confinement)));
end

function db = field_db(u,referenceAmplitude)
    db = 20*log10(max(abs(u),realmin)/referenceAmplitude);
end

function ratioDb = mean_intensity_ratio_db(x,intensityD,intensityS)
    % Ratio of range-averaged LINEAR intensities, not the mean of dB ratios.
    ratioDb = 10*log10(max(trapz(x,intensityD),realmin)/ ...
        max(trapz(x,intensityS),realmin));
end

function intervals = dominance_intervals(x,deltaDb)
    % Contiguous sampled-grid signs; endpoints are not interpolated.
    state=zeros(size(deltaDb));
    state(deltaDb>1e-6)=1;
    state(deltaDb<-1e-6)=-1;
    starts=[1;find(diff(state)~=0)+1];
    ends=[starts(2:end)-1;numel(x)];
    relation=strings(numel(starts),1);
    for k=1:numel(starts)
        if state(starts(k))>0
            relation(k)="Ducted stronger";
        elseif state(starts(k))<0
            relation(k)="Standard stronger";
        else
            relation(k)="Equal within 1e-6 dB";
        end
    end
    intervals=table(x(starts),x(ends),relation,ends-starts+1, ...
        'VariableNames',{'StartSampleKm','EndSampleKm', ...
        'ReceiverFieldRelation','SampleCount'});
end

function write_summary(folder,windowKm,ratioDb,ductPct,standardPct, ...
        checks,colorLimits,referenceAmplitude)
    fid=fopen(fullfile(folder,'WP007_run_summary.txt'),'w');
    assert(fid>0,'WP007:Output','Cannot write the run summary.');
    cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'WP-007: ducted versus standard atmosphere\n');
    fprintf(fid,['3.5 GHz; idealized 60 m / 20 M-unit duct; ' ...
        'Tx 15 m; Rx 40 m; 0-100 km.\n']);
    fprintf(fid,['Only M(z) changes: duct M0-(20/60)*min(z,60)' ...
        '+0.118*max(z-60,0); standard M0+0.118*z.\n']);
    fprintf(fid,['Both use the same unit-integral Gaussian launch, ' ...
        'horizontal PEC, 50 m/0.25 m steps, 2000 m ceiling, ' ...
        '600 m sponge start, and 5-degree angular cutoff.\n']);
    fprintf(fid,'Common launch-peak normalization amplitude: %.12g\n', ...
        referenceAmplitude);
    fprintf(fid,['Pointwise delta = 10*log10(|u_duct(r,40)|^2/' ...
        '|u_standard(r,40)|^2). Positive favors the duct at that ' ...
        'sampled receiver location.\n']);
    fprintf(fid,['Fixed %.1f-%.1f km mean ratio = ' ...
        '10*log10(trapz(r,|u_duct|^2)/' ...
        'trapz(r,|u_standard|^2)) = %+.6f dB.\n'], ...
        windowKm(1),windowKm(2),ratioDb);
    fprintf(fid,['Within that window, ducted field is stronger ' ...
        'at %.3f%% of sampled ranges; standard field is stronger ' ...
        'at %.3f%%. These are spatial sample counts, not ' ...
        'probabilities or coverage.\n'],ductPct,standardPct);
    if ratioDb>0
        fprintf(fid,['The ducted case has greater spatially averaged ' ...
            'receiver-height intensity in this model/window.\n']);
    elseif ratioDb<0
        fprintf(fid,['The standard case has greater spatially averaged ' ...
            'receiver-height intensity in this model/window.\n']);
    else
        fprintf(fid,['The spatially averaged receiver-height ' ...
            'intensities are equal at displayed precision.\n']);
    end
    fprintf(fid,['Field-map color limits: [%.1f, %.1f] dB in BOTH ' ...
        'atmospheres and every GIF frame. Map height is 0-160 m; ' ...
        'the full complex grids are in WP007_results.mat.\n'],colorLimits);
    fprintf(fid,['The numerical-check table varies dx, dz, ceiling, ' ...
        'and sponge start, always in both atmospheres. RMS changes ' ...
        'exclude baseline samples below -60 dB in either receiver ' ...
        'field; the mean-ratio check uses the full fixed window.\n']);
    for k=1:height(checks)
        fprintf(fid,['  %s: mean-ratio change %+.6f dB; ' ...
            'duct/standard mean changes %+.6f/%+.6f dB; ' ...
            'delta RMS %.6f dB; delta max %.6f dB; ' ...
            'top-guard duct %.3g, standard %.3g.\n'], ...
            char(checks.Variant(k)),checks.MeanRatioChangeDb(k), ...
            checks.DuctMeanIntensityChangeDb(k), ...
            checks.StandardMeanIntensityChangeDb(k), ...
            checks.DeltaRmsChangeDb(k),checks.DeltaMaxChangeDb(k), ...
            checks.DuctMaxTopGuardFraction(k), ...
            checks.StandardMaxTopGuardFraction(k));
    end
    fprintf(fid,['The plotted fields are relative 2-D PE quantities. ' ...
        'No received-power calibration, link budget, noise, traffic, ' ...
        'reliability, or temporal evolution is modeled. The ideal sea, ' ...
        'source, refractivity profiles and numerical absorber limit ' ...
        'physical generalization. Review checks before publication.\n']);
end

function make_static_figure(v,folder)
    [fig,~]=comparison_layout(v,false);
    add_result_band(fig,v);
    add_footer(fig,'WP-007','Mohammed Banafaa');
    savefig(fig,fullfile(folder,'WP007_Final.fig'));
    exportgraphics(fig,fullfile(folder,'WP007_Final.png'), ...
        'Resolution',100);
    close(fig);
end

function make_animation(v,folder,spacingKm,delaySeconds)
    [fig,h]=comparison_layout(v,true);
    positions=[0.08 0.302 0.524 0.746];
    cards=gobjects(4,1);
    for k=1:4
        cards(k)=annotation(fig,'textbox', ...
            [positions(k) 0.819 0.174 0.068], ...
            'String','', 'EdgeColor',[0.82 0.88 0.94], ...
            'BackgroundColor',[0.95 0.97 0.99], ...
            'FontName','Arial','FontSize',14, ...
            'FontWeight','bold','Color',[0.06 0.22 0.43], ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','middle');
    end
    add_result_band(fig,v);
    add_footer(fig,'WP-007','Mohammed Banafaa');
    stride=max(1,round(spacingKm/(v.x(2)-v.x(1))));
    frames=unique([1:stride:numel(v.x),numel(v.x)]);
    assert(numel(frames)>1,'WP007:GIF', ...
        'The animation requires multiple range samples.');
    gifFile=fullfile(folder,'WP007_Final.gif');
    tempFrame=fullfile(folder,'WP007_frame_temp.png');
    for j=1:numel(frames)
        ii=frames(j);
        set(h.scanD,'XData',[v.x(ii) v.x(ii)]);
        set(h.scanS,'XData',[v.x(ii) v.x(ii)]);
        set(h.rxD,'XData',v.x(ii));
        set(h.rxS,'XData',v.x(ii));
        set(h.fieldD,'XData',v.x(ii),'YData',v.ductDb(ii));
        set(h.fieldS,'XData',v.x(ii),'YData',v.standardDb(ii));
        set(h.delta,'XData',v.x(ii),'YData',v.enhancementDb(ii));
        set(h.scanField,'XData',[v.x(ii) v.x(ii)]);
        set(h.scanDelta,'XData',[v.x(ii) v.x(ii)]);
        set(cards(1),'String',sprintf('RANGE\n%.1f km',v.x(ii)));
        set(cards(2),'String',sprintf('DUCTED\n%.2f dB',v.ductDb(ii)));
        set(cards(3),'String',sprintf('STANDARD\n%.2f dB', ...
            v.standardDb(ii)));
        set(cards(4),'String',sprintf('DUCT / STANDARD\n%+.2f dB', ...
            v.enhancementDb(ii)));
        drawnow;
        if abs(v.x(ii)-50)<1e-9
            savefig(fig,fullfile(folder,'WP007_Animation_Layout.fig'));
        end
        % Frame export avoids display-dependent cropping on a laptop.
        exportgraphics(fig,tempFrame,'Resolution',100);
        rgb=imread(tempFrame);
        if j==1
            [indexed,palette]=rgb2ind(rgb,256,'nodither');
        else
            indexed=rgb2ind(rgb,palette,'nodither');
        end
        if j==1
            imwrite(indexed,palette,gifFile,'gif', ...
                'LoopCount',Inf,'DelayTime',delaySeconds);
        else
            imwrite(indexed,palette,gifFile,'gif', ...
                'WriteMode','append','DelayTime',delaySeconds);
        end
    end
    if isfile(tempFrame), delete(tempFrame); end
    close(fig);
    info=imfinfo(gifFile);
    assert(numel(info)>1,'WP007:GIF', ...
        'The exported GIF contains fewer than two frames.');
    fprintf('Animated GIF: %d spatial-sampling frames.\n',numel(info));
end

function [fig,h]=comparison_layout(v,animated)
    % One spatial solution per atmosphere. Layout changes only to reserve
    % four readout cards in the animated version; data and colors do not.
    navy=[0.06 0.22 0.43];
    blue=[0.10 0.38 0.67];
    grey=[0.39 0.48 0.57];
    orange=[0.88 0.43 0.12];
    muted=[0.36 0.42 0.49];
