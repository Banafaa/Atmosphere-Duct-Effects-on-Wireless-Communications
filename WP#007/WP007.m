    cb.Label.String='Relative PE field (dB)';
    cb.Label.FontName='Arial';
    cb.Label.FontSize=11;

    add_text(fig,[0.08 titleBottomY 0.40 0.022], ...
        'Field at the same 40 m receiver height',15,navy,true);
    add_text(fig,[0.57 titleBottomY 0.34 0.022], ...
        'Ducted minus standard (dB)',15,navy,true);
    axField=axes('Parent',fig,'Units','normalized', ...
        'Position',[0.08 bottomY 0.40 bottomH]);
    shade_analysis_window(axField,v.windowKm,v.fieldSpanDb);
