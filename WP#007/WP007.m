        'String',rightLabel,'EdgeColor','none', ...
        'FontName','Arial','FontSize',11, ...
        'Color',[0.36 0.42 0.49], ...
        'HorizontalAlignment','right');
end

function add_text(fig,position,message,fontSize,ink,isBold)
    if isBold, weight='bold'; else, weight='normal'; end
    annotation(fig,'textbox',position,'String',message, ...
        'EdgeColor','none','FontName','Arial', ...
        'FontSize',fontSize,'FontWeight',weight,'Color',ink);
end
