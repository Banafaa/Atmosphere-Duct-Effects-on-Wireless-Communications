        'Ducted vs. Standard Atmosphere',26,navy,true);
    add_text(fig,[0.08 0.911 0.84 0.025], ...
        '3.5 GHz | Tx: 15 m | Rx: 40 m | Idealized smooth sea', ...
        15,muted,false);
    annotation(fig,'textbox',[0.69 0.911 0.23 0.025], ...
        'String','Spatial sampling, not temporal fading', ...
        'EdgeColor','none','FontName','Arial','FontSize',10.5, ...
        'Color',muted,'HorizontalAlignment','right');
    if animated
        mapY=0.519; mapH=0.229;
        bottomY=0.198; bottomH=0.211;
        titleMapY=0.771; titleBottomY=0.433;
    else
        mapY=0.550; mapH=0.257;
        bottomY=0.211; bottomH=0.213;
        titleMapY=0.830; titleBottomY=0.448;
    end
    add_text(fig,[0.08 titleMapY 0.38 0.024], ...
        'Surface-based duct: 60 m, 20 M-units',15,navy,true);
    add_text(fig,[0.55 titleMapY 0.36 0.024], ...
        'Standard atmosphere: +0.118 M/m',15,navy,true);

    axD=axes('Parent',fig,'Units','normalized', ...
        'Position',[0.08 mapY 0.375 mapH]);
    imagesc(axD,v.x,v.z,v.ductMapDb); hold(axD,'on');
    map_style(axD,v);
    plot(axD,[0 v.x(end)],[v.ductTopM v.ductTopM], ...
