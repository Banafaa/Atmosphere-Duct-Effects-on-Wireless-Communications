            'MarkerSize',10);
        h.rxS=plot(axS,0,v.rxHeightM,'o', ...
            'MarkerFaceColor',orange,'MarkerEdgeColor','w', ...
            'MarkerSize',10);
        h.scanField=plot(axField,[0 0],v.fieldSpanDb, ...
            ':','Color',orange,'LineWidth',1.1);
        h.fieldD=plot(axField,0,v.ductDb(1),'o', ...
            'MarkerFaceColor',blue,'MarkerEdgeColor','w', ...
            'MarkerSize',9);
        h.fieldS=plot(axField,0,v.standardDb(1),'o', ...
            'MarkerFaceColor',grey,'MarkerEdgeColor','w', ...
            'MarkerSize',9);
