function h=add_bar(ax,interval,y,height,fill,edge)
    % Rectangle extends over the exact half-open time interval.
    h=rectangle(ax,'Position', ...
        [interval(1),y-height/2,diff(interval),height], ...
        'FaceColor',fill,'EdgeColor',edge,'LineWidth',1.1);
end

function draw_tower(ax,x,ink)
    % Minimal coastal gNB glyph, intentionally schematic.
    plot(ax,[x x],[.35 .67],'Color',ink,'LineWidth',3);
    plot(ax,[x-.025 x+.025],[.35 .35],'Color',ink,'LineWidth',3);
    plot(ax,[x-.025 x+.025],[.54 .54],'Color',ink,'LineWidth',2);
    plot(ax,[x-.027 x+.027],[.61 .61],'Color',ink,'LineWidth',2);
    plot(ax,x,.67,'o','MarkerFaceColor',ink, ...
        'MarkerEdgeColor','w','MarkerSize',7);
end

function label(fig,position,str,fontSize,color,bold,alignment)
    if bold, weight='bold'; else, weight='normal'; end
    annotation(fig,'textbox',position,'String',str, ...
        'EdgeColor','none','FontName','Arial', ...
        'FontSize',fontSize,'FontWeight',weight,'Color',color, ...
        'HorizontalAlignment',alignment,'Interpreter','none');
end

function update_arrival(h,caseData,c)
    % The geometry and both schedules remain fixed while L_path changes.
    set(h.remote,'Position', ...
        [caseData.arrivalStartUs,1.64-.21,diff(c.dlUs),.42]);
    set(h.arrivalLabel,'Position', ...
        [caseData.arrivalStartUs+15,1.64,0]);
    if caseData.overlapUs>0
        set(h.overlapArrival,'Position', ...
            [caseData.overlapStartUs,1.64-.21,caseData.overlapUs,.42], ...
            'Visible','on');
        set(h.overlapVictim,'Position', ...
            [caseData.overlapStartUs,.70-.21,caseData.overlapUs,.42], ...
            'Visible','on');
        assert(abs(caseData.overlapEndUs-caseData.overlapStartUs- ...
            caseData.overlapUs)<1e-8, ...
            'WP008:VisualOverlap','Displayed highlight differs from overlap.');
    else
        set(h.overlapArrival,'Visible','off');
        set(h.overlapVictim,'Visible','off');
    end
    set(h.cards(1),'String',sprintf('PATH LENGTH\n%.0f km', ...
        caseData.pathKm));
    set(h.cards(2),'String',sprintf('DELAY\n%.1f %cs', ...
        caseData.tauUs,char(181)));
    set(h.cards(3),'String',sprintf('GUARD\n%.0f %cs', ...
        diff(c.guardUs),char(181)));
    set(h.cards(4),'String',sprintf('OVERLAP\n%.1f %cs', ...
        caseData.overlapUs,char(181)));
end

function matches=card_text_matches(card,expected)
    % Textbox String may be a character vector, character matrix, or
    % cell array of lines. Normalize it before the scalar assertion.
    actual=get(card,'String');
    if iscell(actual)
        actual=strjoin(actual,char(10));
    elseif isstring(actual)
        actual=strjoin(cellstr(actual),char(10));
    elseif ischar(actual) && ~isrow(actual)
        actual=strjoin(cellstr(actual),char(10));
    end
    matches=isequal(actual,expected);
end

function filename=render_temporary_png(fig)
    % Print to a unique file before replacing a final asset. Explicit
    % 19-by-10.5-inch paper at 100 dpi gives a 1900-by-1050-pixel canvas.
    filename=[tempname '.png'];
    try
        print(fig,filename,'-dpng','-r100');
    catch err
        error('WP008:PNGExport', ...
            ['PNG rendering failed: %s. Check MATLAB graphics support ' ...
            'and write access to its temporary folder.'],err.message);
    end
    if ~isfile(filename)
        error('WP008:PNGExport','MATLAB did not create %s.',filename);
    end
end

function publish_file(temporaryFile,finalFile)
    [ok,msg]=movefile(temporaryFile,finalFile,'f');
    if ~ok
        error('WP008:OutputLocked', ...
            ['Rendered file remains at %s, but MATLAB could not ' ...
            'replace %s (%s). Close viewers using the old output ' ...
            'and check folder write access.'], ...
            temporaryFile,finalFile,msg);
    end
end
