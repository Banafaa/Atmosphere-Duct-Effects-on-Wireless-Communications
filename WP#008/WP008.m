%% WP008 - Remote downlink arrival during a TDD uplink interval
% Wireless Propagation Visuals — WP-008
% Author: Mohammed Banafaa
%
% Purpose
%   Illustrate the timing mechanism of remote gNB downlink arrival at a
%   synchronized victim gNB. This is an interval-overlap calculation, not
%   an electromagnetic propagation or interference-power simulation.
%
% Model and illustrative inputs
%   tau approximately equals L_path/c, with assumed signal-path length
%   L_path and vacuum light speed c = 299792458 m/s. The assumed 1 ms
%   cycle has DL [0,500) us, guard [500,650) us, and UL [650,1000) us.
%   A 30 km path is the no-overlap reference, a 100 km path is the static
%   example, and the GIF sweeps 20:2:140 km. All timing choices are
%   illustrative; they are not prescribed NR symbol or guard settings.
%   The paths are separate hypothetical scenarios, not a time-varying duct.
%   The 3.5 GHz carrier identifies an NR n78 TDD application. It is not
%   used in the geometric propagation-delay calculation.
%
% Requirements and use
%   MATLAB R2024b or later; base MATLAB only, no input files or toolboxes.
%   Save as WP008.m and run WP008 from any current MATLAB folder. The
%   script creates Figures next to itself and generates WP008_Final.png,
%   WP008_Final.gif, WP008_timing_results.csv, and WP008_run_summary.txt.
%
% Limits
%   Timing coincidence does not establish received interference power,
%   SINR, uplink outage, or measured network behaviour. A sufficiently
%   received signal on overlapping radio resources is also necessary.
%   The coastal path drawing is conceptual and not to geographic scale.
%
% References
%   3GPP TS 38.300 V17.3.0, sec. 17.1 (Remote Interference Management).
%   ITU-R Report M.2559-0 (12/2025), tropospheric-duct interference.
%   3GPP TS 38.104 V17.11.0, NR operating band n78.

clear; close all; clc;

%% 1. Reproducible illustrative configuration
if verLessThan('matlab','24.2')
    error('WP008:Version','WP008.m requires MATLAB R2024b or later.');
end
required = {'print','imread','imwrite','imfinfo','rgb2ind', ...
    'writetable','tempname','movefile'};
for k = 1:numel(required)
    if exist(required{k},'file')==0 && exist(required{k},'builtin')==0
        error('WP008:Dependency', ...
            'Base MATLAB function %s is unavailable.',required{k});
    end
end
scriptDir=fileparts(mfilename('fullpath'));
if isempty(scriptDir)
    error('WP008:ScriptPath','Save the source as WP008.m before running it.');
end
figuresDir=fullfile(scriptDir,'Figures');
if ~isfolder(figuresDir)
    [ok,msg]=mkdir(figuresDir);
    if ~ok
        error('WP008:OutputFolder','Could not create Figures: %s',msg);
    end
end

cfg=struct();
cfg.carrierGHz=3.5;                   % NR n78 context; not in tau.
cfg.cMps=299792458;                   % Approximate path delay uses c.
cfg.cycleUs=1000;                     % Illustrative aligned 1 ms cycle.
cfg.dlUs=[0 500];                     % Aggressor transmit DL.
cfg.guardUs=[500 650];                % Victim switching guard.
cfg.ulUs=[650 1000];                  % Victim receiving UL.
cfg.shortPathKm=30;                   % No-overlap comparison.
cfg.examplePathKm=100;                % Selected static illustration.
cfg.sweepPathKm=(20:2:140).';         % Separate path scenarios for GIF.
cfg.gifDelaySeconds=0.12;
validate_configuration(cfg);

%% 2. Derive arrival intervals, overlaps, and check boundary cases
shortCase=timing_case(cfg.shortPathKm,cfg);
exampleCase=timing_case(cfg.examplePathKm,cfg);
zeroCase=timing_case(0,cfg);
edgePathKm=cfg.cMps*((cfg.guardUs(2)-cfg.guardUs(1))*1e-6)/1000;
edgeCase=timing_case(edgePathKm,cfg);
tolUs=1e-8;
assert(zeroCase.overlapUs<=tolUs && edgeCase.overlapUs<=tolUs, ...
    'WP008:Boundary','Zero delay and delay equal to guard must not overlap UL.');
assert(shortCase.overlapUs<=tolUs && exampleCase.overlapUs>tolUs, ...
    'WP008:Examples','The chosen short/long paths must contrast overlap.');
assert(exampleCase.tauUs>shortCase.tauUs && ...
    abs(exampleCase.arrivalEndUs-exampleCase.arrivalStartUs- ...
    diff(cfg.dlUs))<tolUs, ...
    'WP008:Units','Path-delay units or DL interval are inconsistent.');

n=numel(cfg.sweepPathKm);
sweepCases=repmat(timing_case(cfg.sweepPathKm(1),cfg),n,1);
for k=1:n
    sweepCases(k)=timing_case(cfg.sweepPathKm(k),cfg);
end
pathKm=reshape([sweepCases.pathKm],[],1);
delayUs=reshape([sweepCases.tauUs],[],1);
arrivalStartUs=reshape([sweepCases.arrivalStartUs],[],1);
arrivalEndUs=reshape([sweepCases.arrivalEndUs],[],1);
overlapStartUs=reshape([sweepCases.overlapStartUs],[],1);
overlapEndUs=reshape([sweepCases.overlapEndUs],[],1);
overlapUs=reshape([sweepCases.overlapUs],[],1);
isShort=abs(pathKm-cfg.shortPathKm)<1e-9;
isExample=abs(pathKm-cfg.examplePathKm)<1e-9;
assert(nnz(isShort)==1 && nnz(isExample)==1 && ...
    abs(overlapUs(isExample)-exampleCase.overlapUs)<tolUs, ...
    'WP008:Consistency','Static example and sweep data do not match.');
assert(all(overlapUs>=0) && ...
    all(overlapUs<=min(diff(cfg.dlUs),diff(cfg.ulUs))+tolUs), ...
    'WP008:Overlap','An overlap exceeds its source intervals.');

results=table(pathKm,delayUs, ...
    repmat(diff(cfg.guardUs),n,1),arrivalStartUs,arrivalEndUs, ...
    overlapStartUs,overlapEndUs,overlapUs,isShort,isExample, ...
    'VariableNames',{'PathLengthKm','PropagationDelayUs', ...
    'GuardPeriodUs','ArrivalStartUs','ArrivalEndUs', ...
    'OverlapStartUs','OverlapEndUs','OverlapUs', ...
    'IsNoOverlapExample','IsOverlapExample'});
writetable(results,fullfile(figuresDir,'WP008_timing_results.csv'));
write_run_summary(fullfile(figuresDir,'WP008_run_summary.txt'), ...
    cfg,shortCase,exampleCase,edgePathKm,n);

%% 3. Render one static case and a synchronized parameter-sweep GIF
[fig,h]=make_layout(cfg);
update_arrival(h,exampleCase,cfg);
drawnow;
pngFile=fullfile(figuresDir,'WP008_Final.png');
temporaryPng=render_temporary_png(fig);
pngInfo=imfinfo(temporaryPng);
assert(pngInfo.Width>=1800 && pngInfo.Width<=2000, ...
    'WP008:ImageWidth', ...
    'PNG width is %d px; expected approximately 1900 px.',pngInfo.Width);
publish_file(temporaryPng,pngFile);

% Derive one palette from the orange-overlap static scene, so GIF frames
% without overlap do not cause the orange emphasis color to disappear.
staticRgb=imread(pngFile);
[~,palette]=rgb2ind(staticRgb,256,'nodither');
temporaryGif=[tempname '.gif'];
set(h.gifNote,'Visible','on');
firstIndexed=[];
for k=1:n
    update_arrival(h,sweepCases(k),cfg);
    drawnow;
    assert(isequal(get(h.timeAxis,'XLim'),[0 cfg.cycleUs]) && ...
        card_text_matches(h.cards(1), ...
        sprintf('PATH LENGTH\n%.0f km',sweepCases(k).pathKm)) && ...
        card_text_matches(h.cards(2), ...
        sprintf('DELAY\n%.1f %cs',sweepCases(k).tauUs,char(181))) && ...
        card_text_matches(h.cards(3), ...
        sprintf('GUARD\n%.0f %cs',diff(cfg.guardUs),char(181))) && ...
        card_text_matches(h.cards(4), ...
        sprintf('OVERLAP\n%.1f %cs',sweepCases(k).overlapUs,char(181))), ...
        'WP008:FrameReadouts', ...
        'Timeline scale or frame readouts differ from the timing result.');
    framePng=render_temporary_png(fig);
    frameInfo=imfinfo(framePng);
    assert(frameInfo.Width==pngInfo.Width && ...
        frameInfo.Height==pngInfo.Height, ...
        'WP008:FrameSize','GIF frame dimensions changed during export.');
    rgb=imread(framePng);
    delete(framePng);
    indexed=rgb2ind(rgb,palette,'nodither');
    if k==1
        firstIndexed=indexed;
        imwrite(indexed,palette,temporaryGif,'gif', ...
            'LoopCount',Inf,'DelayTime',cfg.gifDelaySeconds);
    else
        imwrite(indexed,palette,temporaryGif,'gif', ...
            'WriteMode','append','DelayTime',cfg.gifDelaySeconds);
    end
end
assert(~isequal(firstIndexed,indexed), ...
    'WP008:GifMotion','The first and last rendered frames are identical.');
gifInfo=imfinfo(temporaryGif);
assert(numel(gifInfo)==n && n>1, ...
    'WP008:GifFrames','The GIF does not contain the complete sweep.');
assert(all(strcmp({gifInfo.Format},'GIF')), ...
    'WP008:GifFormat','The output is not encoded as a GIF.');
assert(all([gifInfo.Width]==pngInfo.Width) && ...
    all([gifInfo.Height]==pngInfo.Height), ...
    'WP008:GifSize','GIF dimensions changed across frames.');
gifFile=fullfile(figuresDir,'WP008_Final.gif');
publish_file(temporaryGif,gifFile);
close(fig);
fprintf('WP-008: no-overlap path %.0f km; selected path %.0f km.\n', ...
    cfg.shortPathKm,cfg.examplePathKm);
fprintf('Selected delay %.3f us; guard %.0f us; overlap %.3f us.\n', ...
    exampleCase.tauUs,diff(cfg.guardUs),exampleCase.overlapUs);
fprintf('Saved PNG, %d-frame GIF, and timing data in %s\n',n,figuresDir);

%% Local functions
function validate_configuration(c)
    % One aligned cycle is drawn. Keep the whole arriving DL interval in it
    % so an edited sweep cannot silently hide a periodic wrap-around.
    vals=[c.carrierGHz c.cMps c.cycleUs c.dlUs c.guardUs c.ulUs ...
        c.shortPathKm c.examplePathKm c.sweepPathKm(:).'];
    assert(all(isfinite(vals)) && c.cMps>0 && c.carrierGHz>0 && ...
        c.cycleUs>0 && all(c.sweepPathKm>=0), ...
        'WP008:Config','All path lengths and timing inputs must be finite.');
    assert(c.dlUs(1)==0 && c.dlUs(2)==c.guardUs(1) && ...
        c.guardUs(2)==c.ulUs(1) && c.ulUs(2)==c.cycleUs && ...
        all(diff(c.dlUs)>0) && all(diff(c.guardUs)>0) && ...
        all(diff(c.ulUs)>0), ...
        'WP008:Schedule','The DL, guard, and UL intervals must tile one cycle.');
    assert(numel(c.sweepPathKm)>1 && ...
        all(diff(c.sweepPathKm)>0) && ...
        any(c.sweepPathKm==c.shortPathKm) && ...
        any(c.sweepPathKm==c.examplePathKm), ...
        'WP008:Sweep','The sweep must contain both illustrated paths.');
    longestKm=max([c.sweepPathKm(:);c.shortPathKm;c.examplePathKm]);
    maximumArrivalEndUs=c.dlUs(2)+(longestKm*1000/c.cMps)*1e6;
    assert(maximumArrivalEndUs<c.cycleUs, ...
        'WP008:CycleWrap', ...
        ['The chosen path would wrap the arrival into the next TDD ' ...
        'cycle. Shorten the path sweep or extend the modeled cycle.']);
end

function out=timing_case(pathKm,c)
    % Half-open intervals make a contact exactly at UL start a zero
    % duration event. L_path is a stipulated path length, not a ray trace.
    assert(isfinite(pathKm) && pathKm>=0, ...
        'WP008:Path','Path length must be nonnegative and finite.');
    out.pathKm=pathKm;
    out.tauUs=(pathKm*1000/c.cMps)*1e6;
    out.arrivalStartUs=c.dlUs(1)+out.tauUs;
    out.arrivalEndUs=c.dlUs(2)+out.tauUs;
    left=max(out.arrivalStartUs,c.ulUs(1));
    right=min(out.arrivalEndUs,c.ulUs(2));
    out.overlapUs=max(0,right-left);
    if out.overlapUs>0
        out.overlapStartUs=left;
        out.overlapEndUs=right;
    else
        out.overlapStartUs=NaN;
        out.overlapEndUs=NaN;
    end
end

function write_run_summary(filename,c,shortCase,exampleCase,edgePathKm,n)
    fid=fopen(filename,'w');
    if fid<0
        error('WP008:Summary','Cannot write %s.',filename);
    end
    cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'WP-008 illustrative remote-DL timing\n');
    fprintf(fid,'Application: 3.5 GHz NR n78; carrier does not set delay.\n');
    fprintf(fid,'Approximation: tau = L_path / c, c = %.0f m/s.\n',c.cMps);
    fprintf(fid,['Assumed aligned cycle (not a standard-prescribed ' ...
        'configuration): %.0f us.\n'],c.cycleUs);
    fprintf(fid,'Aggressor DL: [%.0f,%.0f) us.\n',c.dlUs);
    fprintf(fid,'Guard: [%.0f,%.0f) us, duration %.0f us.\n', ...
        c.guardUs,diff(c.guardUs));
    fprintf(fid,'Victim UL: [%.0f,%.0f) us.\n',c.ulUs);
    fprintf(fid,['No-overlap reference: L_path %.0f km; delay %.6f us; ' ...
        'arrival [%.6f,%.6f) us; UL overlap %.6f us.\n'], ...
        shortCase.pathKm,shortCase.tauUs, ...
        shortCase.arrivalStartUs,shortCase.arrivalEndUs, ...
        shortCase.overlapUs);
    fprintf(fid,['Selected example: L_path %.0f km; delay %.6f us; ' ...
        'arrival [%.6f,%.6f) us; UL overlap %.6f us.\n'], ...
        exampleCase.pathKm,exampleCase.tauUs, ...
        exampleCase.arrivalStartUs,exampleCase.arrivalEndUs, ...
        exampleCase.overlapUs);
    fprintf(fid,'Guard-boundary path length: %.6f km; zero overlap.\n', ...
        edgePathKm);
    fprintf(fid,'GIF: %d separate path-length scenarios, %.0f-%.0f km.\n', ...
        n,c.sweepPathKm(1),c.sweepPathKm(end));
    fprintf(fid,['Temporal intersection alone does not determine ' ...
        'received interference power, SINR, or uplink outage.\n']);
end

